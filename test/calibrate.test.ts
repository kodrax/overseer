import { writeFileSync } from 'node:fs';
import { describe, expect, it } from 'vitest';
import { type Centering, DEFAULT_MODEL, MODEL_REGISTRY, TransformersEmbedder } from '../src/core/embeddings.js';
import { VEC_TABLES, type VecTable } from '../src/core/migrations.js';
import { dot } from '../src/core/search.js';
import {
  PAIR_ITEMS,
  PAIRS,
  type PairClass,
  queryVectors,
  REGISTRY,
  registryScorer,
  type Scorer,
  type StoredVectors,
  storedVectors,
  vectorSum,
} from './helpers/pairs.js';

const REFERENCE_FILE = new URL('../src/core/reference-means.ts', import.meta.url);
const PRIOR = MODEL_REGISTRY[DEFAULT_MODEL]!.centering!.prior;
/** Share of registry items whose nearest neighbour may be classed duplicate (the registry has no duplicates). */
const MAX_NEAREST_FALSE_POSITIVES = 0.05;
/** Share of registry pairs from different components that may be classed related. */
const MAX_OTHER_COMPONENT_RELATED = 0.05;

const round2 = (value: number) => Math.round(value * 100) / 100;
const mean = (values: number[]) => values.reduce((sum, value) => sum + value, 0) / values.length;
const share = (values: number[], threshold: number) => values.filter((value) => value >= threshold).length / values.length;
const pct = (value: number) => `${(value * 100).toFixed(0)}%`.padStart(4);

function stats(label: string, values: number[]): string {
  const sorted = [...values].sort((a, b) => a - b);
  const at = (p: number) => sorted[Math.floor(p * (sorted.length - 1))]!.toFixed(3);
  return `${label.padEnd(28)} n=${String(values.length).padEnd(5)} mean=${mean(values).toFixed(3)} min=${at(0)} p10=${at(0.1)} p50=${at(0.5)} p90=${at(0.9)} max=${at(1)}`;
}

/** Mean vector per vec table over every calibration text. */
function referenceMeans(corpora: StoredVectors[]): Record<VecTable, Float32Array> {
  return Object.fromEntries(
    VEC_TABLES.map((table) => {
      const total = vectorSum(corpora.flatMap((corpus) => corpus[table]));
      return [table, Float32Array.from(total.sum, (value) => value / total.n)];
    }),
  ) as Record<VecTable, Float32Array>;
}

function writeReference(model: string, reference: Record<VecTable, Float32Array>): void {
  const base64 = (vector: Float32Array) => Buffer.from(vector.buffer, vector.byteOffset, vector.byteLength).toString('base64');
  writeFileSync(
    REFERENCE_FILE,
    [
      '// Generated by `npm run calibrate` (test/calibrate.test.ts): mean float32 vector per vec table, base64, over the',
      '// calibration corpora (test/fixtures/similarity-pairs.json sides and test/fixtures/registry-pairs.json items).',
      "import type { VecTable } from './migrations.js';",
      '',
      'export const REFERENCE_MEANS: Record<string, Record<VecTable, string>> = {',
      `  '${model}': {`,
      ...VEC_TABLES.map((table) => `    ${table}:\n      '${base64(reference[table])}',`),
      '  },',
      '};',
      '',
    ].join('\n'),
  );
}

/** Highest similarity of each item's duplicate-guard query (its statement vector) to any other item. */
function nearest(stored: StoredVectors, scorer: Scorer): number[] {
  return stored.items_statement_vec.map((query, self) => {
    const score = scorer(query);
    return Math.max(...stored.items_vec.map((_, item) => (item === self ? -Infinity : score(item))));
  });
}

// Runs only via `npm run calibrate` (downloads/loads the real model). Regenerates src/core/reference-means.ts.
describe.skipIf(process.env.OVERSEER_CALIBRATE !== '1')('threshold calibration', () => {
  it('prints per-class similarity statistics and suggested thresholds', async () => {
    const embedder = new TransformersEmbedder(DEFAULT_MODEL);
    const { items, duplicates, not_duplicates } = REGISTRY;
    const index = new Map(items.map((item, position) => [item.id, position]));

    const registry = await storedVectors(embedder, items);
    const pairSides = await storedVectors(embedder, PAIR_ITEMS);
    const reference = referenceMeans([registry, pairSides]);
    writeReference(DEFAULT_MODEL, reference);
    const centering: Centering = { reference, prior: PRIOR };
    // Duplicate-guard queries are `title\ndescription`.
    const rewordings = await queryVectors(
      embedder,
      duplicates.map((dup) => `${dup.title}\n${dup.description}`),
    );

    const lines: string[] = [];
    const report = (label: string, values: number[]) => lines.push(stats(label, values));

    // Registry (no duplicates): nearest neighbours, same-component (related) and other-component pairs, rewordings.
    const plainNearest = nearest(registry, registryScorer(registry, undefined));
    const scorer = registryScorer(registry, centering);
    const centeredNearest = nearest(registry, scorer);
    const sameComponent: number[] = [];
    const otherComponent: number[] = [];
    items.forEach((a, self) => {
      const score = scorer(registry.items_statement_vec[self]!);
      items.forEach((b, item) => {
        if (item !== self) (a.component === b.component ? sameComponent : otherComponent).push(score(item));
      });
    });
    let rewordingTop1 = 0;
    const rewordingScores = duplicates.map((dup, position) => {
      const score = scorer(rewordings[position]!);
      const target = index.get(dup.of)!;
      if (items.every((_, item) => item === target || score(item) < score(target))) rewordingTop1++;
      return score(target);
    });
    const crossLanguage = rewordingScores.filter((_, position) => duplicates[position]!.cross_language);

    // Fixture pairs, two ways: all sides as one registry, and each pair alone (a 2-item registry, center ≈ reference).
    const fixtureScorer = registryScorer(pairSides, centering);
    const fixture = { duplicate: [], related: [], unrelated: [] } as Record<PairClass, number[]>;
    const small = { duplicate: [], related: [], unrelated: [] } as Record<PairClass, number[]>;
    PAIRS.forEach((pair, position) => {
      const sides = [2 * position, 2 * position + 1] as const;
      const pairOnly = Object.fromEntries(VEC_TABLES.map((table) => [table, sides.map((side) => pairSides[table][side]!)])) as StoredVectors;
      const pairScorer = registryScorer(pairOnly, centering);
      for (const [item, query] of [
        [0, 1],
        [1, 0],
      ] as const) {
        fixture[pair.class].push(fixtureScorer(pairSides.items_statement_vec[sides[query]]!)(sides[item]));
        small[pair.class].push(pairScorer(pairSides.items_statement_vec[sides[query]]!)(item));
      }
    });

    // KNN pre-selects the top 50 by plain cosine per vec table; the centered top 5 should lie within them.
    let outsideCandidates = 0;
    items.forEach((_, self) => {
      const query = registry.items_statement_vec[self]!;
      const others = items.map((__, item) => item).filter((item) => item !== self);
      const top = (rank: (item: number) => number, k: number) => [...others].sort((a, b) => rank(b) - rank(a)).slice(0, k);
      const candidates = new Set(VEC_TABLES.flatMap((table) => top((item) => dot(registry[table][item]!, query), 50)));
      const score = scorer(query);
      for (const item of top(score, 5)) if (!candidates.has(item)) outsideCandidates++;
    });

    lines.push(`registry: ${items.length} items, ${duplicates.length} rewordings (${crossLanguage.length} Spanish), prior=${PRIOR}`);
    report('plain nearest neighbour', plainNearest);
    report('nearest neighbour', centeredNearest);
    report('same component', sameComponent);
    report('other component', otherComponent);
    report('rewording → original', rewordingScores);
    report('  of which Spanish', crossLanguage);
    lines.push(`rewordings ranking their original first: ${rewordingTop1}/${duplicates.length}`);
    lines.push(
      `BUG-0001 pairs: ${not_duplicates
        .map(([query, stored]) => `${query}→${stored} ${scorer(registry.items_statement_vec[index.get(query)!]!)(index.get(stored)!).toFixed(3)}`)
        .join(', ')}`,
    );
    lines.push(`centered top-5 outside the plain-cosine KNN candidates: ${outsideCandidates}`);
    for (const cls of ['duplicate', 'related', 'unrelated'] as const) report(`fixture ${cls}`, fixture[cls]);
    for (const cls of ['duplicate', 'related', 'unrelated'] as const) report(`2-item fixture ${cls}`, small[cls]);

    lines.push('', 'duplicate ≥  nearest FP  rewordings  fixture dup  fixture rel→dup  2-item dup  2-item rel→dup');
    for (let threshold = 0.5; threshold <= 0.801; threshold += 0.025) {
      lines.push(
        `${threshold.toFixed(3)}       ${pct(share(centeredNearest, threshold))}        ${pct(share(rewordingScores, threshold))}        ${pct(share(fixture.duplicate, threshold))}         ${pct(share(fixture.related, threshold))}            ${pct(share(small.duplicate, threshold))}        ${pct(share(small.related, threshold))}`,
      );
    }
    lines.push('', 'related ≥  same comp  other comp  rewordings  fixture rel  fixture unrel  2-item rel  2-item unrel');
    for (let threshold = 0.2; threshold <= 0.501; threshold += 0.025) {
      lines.push(
        `${threshold.toFixed(3)}      ${pct(share(sameComponent, threshold))}       ${pct(share(otherComponent, threshold))}       ${pct(share(rewordingScores, threshold))}        ${pct(share(fixture.related, threshold))}         ${pct(share(fixture.unrelated, threshold))}         ${pct(share(small.related, threshold))}        ${pct(share(small.unrelated, threshold))}`,
      );
    }

    // Duplicate: lowest threshold keeping registry nearest-neighbour false positives within budget. Related: lowest
    // threshold keeping pairs from different components within budget.
    const lowest = (values: number[], budget: number, from: number) => {
      let threshold = from;
      while (share(values, threshold) > budget) threshold = round2(threshold + 0.01);
      return threshold;
    };
    const duplicate = lowest(centeredNearest, MAX_NEAREST_FALSE_POSITIVES, 0.5);
    const related = lowest(otherComponent, MAX_OTHER_COMPONENT_RELATED, 0);
    lines.push(
      `at those: nearest FP ${pct(share(centeredNearest, duplicate))}, rewordings duplicate ${pct(share(rewordingScores, duplicate))} / related ${pct(share(rewordingScores, related))}, fixture duplicate ${pct(share(fixture.duplicate, duplicate))} / related ${pct(share(fixture.duplicate, related))}, fixture unrelated→related ${pct(share(fixture.unrelated, related))}`,
    );
    const current = MODEL_REGISTRY[DEFAULT_MODEL]!;
    lines.push(
      '',
      `suggested thresholds: duplicate=${duplicate} related=${related} (current: duplicate=${current.duplicate} related=${current.related})`,
    );
    process.stdout.write(`\n${lines.join('\n')}\n`);
    expect(duplicate).toBeGreaterThan(related);
  }, 600_000);
});
