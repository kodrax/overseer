async function seed(service: OverseerService) {
  const r1 = await service.createItem(
    {
      kind: 'requirement',
      title: 'Password reset by email',
      description: 'When a user requests a password reset, the system shall email a single-use link.',
      req_type: 'functional',
      status: 'approved',
      acceptance_criteria: ['Given a registered email, when reset is requested, then a link is sent'],
      tags: ['auth'],
      allow_duplicate: true,
    },
    ctx,
  );
  await service.createItem(
    { kind: 'requirement', title: 'API latency', description: 'p95 under 300 ms', req_type: 'non_functional', nfr_category: 'performance_efficiency', allow_duplicate: true },
    ctx,
  );
  const epic = await service.createItem({ kind: 'epic', title: 'Accounts' }, ctx);
  const story = await service.createItem(
    {
      kind: 'story',
      title: 'Reset forgotten password',
      description: 'As a user I want to reset my password so that I regain access',
      parent_id: 'EPIC-0001',
      links: [{ rel: 'implements', to: 'REQ-0001' }],
    },
    ctx,
  );
  await service.createItem({ kind: 'task', title: 'Email template', parent_id: 'US-0001' }, ctx);
  await service.createItem(
    {
      kind: 'bug',
      title: 'Reset link expired immediately',
      severity: 'major',
      bug_details: { steps: ['Request reset', 'Open link'], expected: 'Form', actual: 'Expired' },
      links: [{ rel: 'affects', to: 'REQ-0001' }],
    },
    ctx,
  );
  await service.updateItem({ id: 'US-0001', status: 'in_progress', comment: 'Started' }, ctx);
  expect([r1.created, epic.created, story.created]).toEqual([true, true, true]);
}

const withoutHeader = (text: string) =>
  text
    .split('\n')
    .filter((line) => !line.startsWith('<!-- Generated by overseer-cli') && !line.includes('"generated_at"'))
    .join('\n');

describe('export', () => {
  it('writes the five files deterministically (header aside)', async () => {
    const service = openService();
    await seed(service);
    const first = service.exportReports();
    expect(first).toEqual({
      out_dir: 'docs/overseer',
      files: ['README.md', 'requirements.md', 'backlog.md', 'history.md', 'overseer.json'].map((file) => `docs/overseer/${file}`),
    });
    const read = () => first.files.map((file) => readFileSync(join(service.root, file), 'utf8'));
    const before = read();
    const header = new RegExp(`^<!-- Generated by overseer-cli ${packageJsonVersion.replaceAll('.', '\\.')} on .+\\. Do not edit; run "overseer export" to regenerate\\. -->$`);
    for (const text of before.slice(0, 4)) expect(text.split('\n')[0]).toMatch(header);
    service.exportReports();
    expect(read().map(withoutHeader)).toEqual(before.map(withoutHeader));

    const [readme, requirements, backlog, history, json] = before as [string, string, string, string, string];
    expect(readme).toContain('[requirements.md](requirements.md)');
    expect(requirements).toContain('| REQ-0001 | Password reset by email | functional |  | should | approved | in_progress | yes |');
    expect(requirements).toContain('### REQ-0001 — Password reset by email');
    expect(requirements).toContain('- [ ] Given a registered email');
    expect(requirements).toContain('- implements ← US-0001 Reset forgotten password (story, in_progress)');
    expect(backlog).toMatch(/- EPIC-0001 Accounts \(open\)\n {2}- US-0001 Reset forgotten password \(in_progress\)\n {4}- TASK-0001 Email template \(backlog\)/);
    expect(backlog).toContain('| BUG-0001 | Reset link expired immediately | major | backlog | REQ-0001 |');
    expect(history.indexOf('in_progress')).toBeLessThan(history.indexOf('| create |'));
    const data = JSON.parse(json) as { format: string; project: { root_name: string }; items: { id: string }[]; links: unknown[]; events: unknown[] };
    expect(data.format).toBe('overseer-export/1');
    expect(data.items.map((item) => item.id)).toEqual(['BUG-0001', 'EPIC-0001', 'REQ-0001', 'REQ-0002', 'TASK-0001', 'US-0001']);
    expect(data.links).toHaveLength(2);
  });

  it('filters history by since and honours out_dir/only', async () => {
    const service = openService();
    await seed(service);
    service.db.prepare("UPDATE events SET at = '2020-01-01T10:00:00+00:00' WHERE seq <= 3").run();
    const result = service.exportReports({ outDir: 'reports/out', only: ['history'], since: '2021-01-01' });
    expect(result).toEqual({ out_dir: 'reports/out', files: ['reports/out/history.md'] });
    const history = readFileSync(join(service.root, 'reports/out/history.md'), 'utf8');
    expect(history).not.toContain('2020-01-01');
    expect(history).toContain('Events since 2021-01-01');
    expect(() => service.exportReports({ since: 'yesterday' })).toThrowError(expect.objectContaining({ code: 'INVALID_INPUT' }));
    expect(() => service.exportReports({ outDir: '../outside' })).toThrowError(expect.objectContaining({ code: 'INVALID_INPUT' }));
  });
});

